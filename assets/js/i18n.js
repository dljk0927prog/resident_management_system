    var STORAGE_KEY = 'resident_lang';
    if (!localStorage.getItem(STORAGE_KEY) && localStorage.getItem('visitor_lang')) {
        try {
            localStorage.setItem(STORAGE_KEY, localStorage.getItem('visitor_lang'));
        } catch (e) {}
    }
    var currentLang = localStorage.getItem(STORAGE_KEY) || 'en';
    if (LANG[currentLang] === undefined) currentLang = 'en';

    function t(key, params) {
        var text = (LANG[currentLang] && LANG[currentLang][key]) || LANG.en[key] || LANG.zh[key] || key;
        if (params && typeof params === 'object') {
            Object.keys(params).forEach(function(k) {
                text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
            });
        }
        return text;
    }

    function getLang() {
        return currentLang;
    }

    function setLang(code) {
        if (!LANG[code]) return;
        currentLang = code;
        try {
            localStorage.setItem(STORAGE_KEY, code);
        } catch (e) {}
        if (typeof applyPage === 'function') {
            applyPage();
        }
        try {
            window.dispatchEvent(new CustomEvent('langChange', { detail: { lang: code } }));
        } catch (e) {}
    }

    function applyPage() {
        document.querySelectorAll('[data-i18n]').forEach(function(el) {
            var key = el.getAttribute('data-i18n');
            var attr = el.getAttribute('data-i18n-attr');
            var text = t(key);
            if (attr) {
                el.setAttribute(attr, text);
            } else {
                el.textContent = text;
            }
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
            el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
        });
        var titleKey = document.body.getAttribute('data-i18n-title');
        if (titleKey) {
            document.title = t(titleKey);
        }
        var htmlLang = { zh: 'zh-CN', en: 'en', ms: 'ms' }[currentLang] || 'en';
        if (document.documentElement) {
            document.documentElement.setAttribute('lang', htmlLang);
        }
    }

    global.LANG = LANG;
    global.t = t;
    global.getLang = getLang;
    global.setLang = setLang;
    global.applyPage = applyPage;
